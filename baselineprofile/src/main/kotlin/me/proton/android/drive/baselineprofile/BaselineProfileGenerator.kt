package me.proton.android.drive.baselineprofile

import androidx.benchmark.macro.junit4.BaselineProfileRule
import org.junit.Rule
import org.junit.Test

class BaselineProfileGenerator {

    @get:Rule
    val rule = BaselineProfileRule()

    @Test
    fun startToHomeTab() = rule.collect(packageName = targetPackageName, includeInStartupProfile = true) {
        startToHomeTab()
        waitForContent()
    }

    @Test
    fun browseHomeTabs() = rule.collect(packageName = targetPackageName) {
        startToHomeTab()
        browseHomeTabs()
    }
}
